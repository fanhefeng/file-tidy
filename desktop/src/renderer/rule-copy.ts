export function ruleText(locale: Locale, key: RuleCopyKey, values: Record<string, string | number> = {}) {
  const message = (locale === "zh-CN" ? zh : en)[key];
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}

const categoryKeys: Record<string, RuleCopyKey> = {
  Images: "categoryImages",
  Videos: "categoryVideos",
  Audios: "categoryAudios",
  Documents: "categoryDocuments",
  Archives: "categoryArchives",
  Fonts: "categoryFonts",
  Code: "categoryCode",
  Data: "categoryData",
  Design: "categoryDesign",
  Others: "categoryOthers",
};

export function ruleCategoryLabel(locale: Locale, category: string) {
  return Object.hasOwn(categoryKeys, category) ? ruleText(locale, categoryKeys[category]) : category;
}

export type { RuleCopyKey };
