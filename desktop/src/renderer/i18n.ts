export function translate(locale: Locale, key: MessageKey, values: MessageValues = {}): string {
  const template: string =
    locale === "en" && Number(values.count) === 1
      ? (singularEnglish[key] ?? english[key])
      : (locale === "zh-CN" ? chinese : english)[key];
  return template.replace(/\{(\w+)\}/g, (match, name) => (Object.hasOwn(values, name) ? String(values[name]) : match));
}

const builtinCategories = new Set([
  "Images",
  "Videos",
  "Audios",
  "Documents",
  "Archives",
  "Fonts",
  "Code",
  "Data",
  "Design",
  "Others",
]);
export function categoryLabel(locale: Locale, name: string) {
  return builtinCategories.has(name) ? translate(locale, name as MessageKey) : name;
}
export function numberLabel(locale: Locale, value: number) {
  return new Intl.NumberFormat(locale).format(value);
}
export function dateLabel(locale: Locale, value: string | Date) {
  return new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(new Date(value));
}
